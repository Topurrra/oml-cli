"""OUI kit: rebuild chosen OUI components and page templates in ANY OutSystems 11 Reactive module, from source.

OUI cannot be referenced across infrastructures (a personal environment and a company one), and Service Studio's IP
protection refuses a copy-paste between them. The components are plain specs, though, so they can be built again in the
target module with `oml apply`. This script makes that spec: the chosen blocks and screens with everything they need
(other blocks, structures, entities, actions, the OuiCore script) and only the CSS those components use.

  python ouikit.py --catalog
      writes kit/catalog.json and kit/catalog.md: every block with what it does, inputs, events, placeholders,
      dependencies and an example of use. Agents read the catalog to choose components.

  python ouikit.py --blocks OuiCard,OuiTableWrap [--screens OuiData] [--flow UI] [--rename Oui=Acme]
                   [--theme <Theme> --current <current.css>] --out <folder>
      writes <folder>/spec.json (+ oui-core.js, oui-kit.css). Then: oml apply <app.oml> <folder>/spec.json <staged.oml>.
      --theme/--current: the theme's CSS now (oml describe <app.oml> <Theme> --css, its styleSheet); the OUI CSS is
      appended to it once (a later run replaces the appended part), so the app's own CSS stays. Without --theme the
      CSS is only written to oui-kit.css for you to add. --new-theme <Name>: for a module with no theme of its own (a new
      app uses OutSystems UI's), a new theme based on OutSystemsUI with the kit CSS, made the module's default theme.

  python ouikit.py --all [--flow UI] [--rename Oui=Acme] --new-theme <Theme> --out <folder>
      every block and every screen, with the whole style sheet. --all-blocks: every block, no screens.
      A chosen page template brings the other templates its menu links to. Links to a screen that is not built are left out,
      and so is the showcase menu, unless you use --all.

  python ouikit.py --pack <folder>
      copies everything this script needs (library, CSS, JavaScript, libraries, catalog, a guide) to a folder of its own,
      so an agent on another machine can use the kit with no access to the OUI module.
"""
import argparse, copy, json, pathlib, re, shutil, sys

HERE = pathlib.Path(__file__).resolve().parent
KIT = HERE / "kit"
MARK = "/* ==== OUI kit (generated by ouikit.py; a later run replaces from here) ==== */"
SUPPORT = ["structures", "staticEntities", "entities", "serverActions", "clientActions"]
TEMPLATE_PREFIX = "OuiTpl"
SHOWCASE_NAV = "OuiShowcaseNav"
# OUI.render.markdown loads these the first time an answer has math or a diagram.
LIBRARIES = {"OuiKatex": "katex.min.js", "OuiMermaid": "mermaid.min.js"}
MARKDOWN_BLOCKS = {"OuiMarkdownView"}
# Layout helpers a screen built with the kit uses around the components: always included.
UTILITIES = {"oui-app", "oui-page", "oui-stack", "oui-row", "oui-grid", "oui-section", "oui-showcase", "oui-contents", "oui-hidden",
             "oui-display", "oui-muted", "oui-sr", "oui-text", "oui-heading", "oui-caption"}


def load():
    lib = json.loads((HERE / "library.json").read_text(encoding="utf-8"))
    css = (HERE / "theme.css").read_text(encoding="utf-8")
    js = (HERE / "js" / "module.js").read_text(encoding="utf-8")
    return lib, css, js


def dump(x):
    return json.dumps(x, ensure_ascii=False)


def block_refs(item):
    text = dump(item)
    return set(re.findall(r'"sourceBlock":\s*"([^"]+)"', text)) | set(re.findall(r'"layout":\s*"([^"]+)"', text))


def screen_links(item, all_screens):
    found = set()

    def visit(w):
        if w.get("type") == "Link" and w.get("onClick") in all_screens:
            found.add(w["onClick"])
        if w.get("kind") == "destination" and w.get("screen") in all_screens:
            found.add(w["screen"])
    walk_widgets(item, visit)
    return found


def with_templates(lib, screens):
    """A chosen template brings the templates its menu links to."""
    by_name = {s["name"]: s for s in lib["screens"]}
    names, chosen = set(by_name), set(screens)
    while True:
        more = {t for n in chosen if n in by_name for t in screen_links(by_name[n], names) if t.startswith(TEMPLATE_PREFIX)} - chosen
        if not more:
            return chosen
        chosen |= more


def calls(widget, actions):
    """True when the widget's click or one of its events runs one of these actions."""
    if widget.get("onClick") in actions:
        return True
    return any(v in actions if isinstance(v, str) else isinstance(v, dict) and v.get("action") in actions for v in (widget.get("events") or {}).values())


def prune_screen(screen, kept_screens, all_screens):
    """Actions that only go to a screen that is not built leave, with the buttons and menu items that run them."""
    def dead(action):
        return any(n.get("kind") == "destination" and n.get("screen") in all_screens and n["screen"] not in kept_screens for n in action.get("flow", []))
    gone = {a["name"] for a in screen.get("actions", []) if dead(a)}
    screen = dict(screen, actions=[a for a in screen.get("actions", []) if a["name"] not in gone])
    return prune(screen, kept_screens, all_screens, gone)


def prune(node, kept_screens, all_screens, gone=frozenset()):
    """Takes out links to screens that are not built, and the showcase menu."""
    if isinstance(node, list):
        out = []
        for w in node:
            if isinstance(w, dict) and w.get("type") == "Link" and w.get("onClick") in all_screens and w["onClick"] not in kept_screens:
                continue
            if isinstance(w, dict) and gone and calls(w, gone):
                continue
            if isinstance(w, dict) and w.get("type") == "BlockInstance" and w.get("sourceBlock") == SHOWCASE_NAV:
                continue
            out.append(prune(w, kept_screens, all_screens, gone))
        return out
    if isinstance(node, dict):
        return {k: prune(v, kept_screens, all_screens, gone) for k, v in node.items()}
    return node


def resolve(lib, blocks, screens):
    """The blocks, screens and support elements the chosen ones need, to a fixed point."""
    by_name = {b["name"]: b for b in lib["blocks"]}
    sc_by_name = {s["name"]: s for s in lib["screens"]}
    unknown = [n for n in blocks if n not in by_name] + [n for n in screens if n not in sc_by_name]
    if unknown:
        sys.exit(f"Unknown block or screen: {', '.join(unknown)}. See kit/catalog.md (python ouikit.py --catalog).")
    want_b, want_s = set(blocks), set(screens)
    support = {k: set() for k in SUPPORT}
    while True:
        items = [by_name[n] for n in want_b] + [sc_by_name[n] for n in want_s] + [e for k in SUPPORT for e in lib.get(k, []) if e["name"] in support[k]]
        text = dump(items)
        more_b = set().union(*[block_refs(i) for i in items]) - want_b if items else set()
        more_s = {k: {e["name"] for e in lib.get(k, []) if re.search(r"\b" + re.escape(e["name"]) + r"\b", text)} - support[k] for k in SUPPORT}
        if not more_b and not any(more_s.values()):
            break
        want_b |= {n for n in more_b if n in by_name}
        for k in SUPPORT:
            support[k] |= more_s[k]
    return want_b, want_s, support


def strip_comments(css):
    return re.sub(r"/\*(?!!).*?\*/", "", css, flags=re.S)


def split_rules(css):
    """Top-level rules: (prelude, body) pairs; body is None for a statement such as @import."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = i
        while j < n and css[j] not in "{;":
            j += 1
        if j >= n:
            break
        prelude = css[i:j].strip()
        if css[j] == ";":
            out.append((prelude, None)); i = j + 1; continue
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{": depth += 1
            elif css[k] == "}": depth -= 1
            k += 1
        out.append((prelude, css[j + 1:k - 1])); i = k
    return out


def slice_css(css, used):
    """Rules whose selector names no oui- class (tokens, base), or names one the components use."""
    def keep(selector):
        names = re.findall(r"\.(oui-[\w-]+)", selector)
        return not names or any(n in used or n.split("__")[0] in used or re.sub(r"--[\w-]+$", "", n) in used for n in names)

    def walk(text):
        parts = []
        for prelude, body in split_rules(text):
            if body is None:
                parts.append(prelude + ";")
            elif re.match(r"@(media|supports|container|layer)\b", prelude):
                inner = walk(body)
                if inner.strip():
                    parts.append(prelude + " {\n" + inner + "\n}")
            elif prelude.startswith("@"):
                parts.append(prelude + " {" + body + "}")
            else:
                sels = [s for s in split_selectors(prelude) if keep(s)]
                if sels:
                    parts.append(", ".join(s.strip() for s in sels) + " {" + body + "}")
        return "\n".join(parts)

    return walk(strip_comments(css))


def split_selectors(prelude):
    """Commas that separate selectors, not the ones inside :is(), :where(), :has() or :not()."""
    out, depth, start = [], 0, 0
    for i, ch in enumerate(prelude):
        if ch == "(": depth += 1
        elif ch == ")": depth -= 1
        elif ch == "," and depth == 0:
            out.append(prelude[start:i]); start = i + 1
    out.append(prelude[start:])
    return out


ENTITY_ACTIONS = ("Create", "CreateOrUpdate", "Update", "Delete", "Get", "GetForUpdate")


def renamer(names, rename, entities=()):
    if not rename:
        return lambda s: s
    old, new = rename.split("=", 1)
    mapping = {n: new + n[len(old):] for n in names if n.startswith(old)}
    # The actions of an entity carry its name: CreateOuiDemoTask becomes CreateAcmeDemoTask.
    mapping.update({v + e: v + new + e[len(old):] for e in entities if e.startswith(old) for v in ENTITY_ACTIONS})
    if not mapping:
        return lambda s: s
    pattern = re.compile(r"\b(" + "|".join(sorted(map(re.escape, mapping), key=len, reverse=True)) + r")\b")
    return lambda s: pattern.sub(lambda m: mapping[m.group(1)], s)


def build(args):
    lib, css, js = load()
    everything = bool(args.all or args.all_blocks)
    blocks = [b["name"] for b in lib["blocks"]] if everything else [b.strip() for b in (args.blocks or "").split(",") if b.strip()]
    screens = [s["name"] for s in lib["screens"]] if args.all else [s.strip() for s in (args.screens or "").split(",") if s.strip()]
    if not args.all:
        screens = sorted(with_templates(lib, screens))
        all_screens = {s["name"] for s in lib["screens"]}
        lib = dict(lib, screens=[prune_screen(s, set(screens), all_screens) for s in copy.deepcopy(lib["screens"])])
        # The showcase menu links to every showcase screen: it exists only to move around OUI itself.
        lib["blocks"] = [b for b in lib["blocks"] if b["name"] != SHOWCASE_NAV or args.all_blocks]
        if args.all_blocks:
            lib["blocks"] = [b for b in lib["blocks"] if b["name"] != SHOWCASE_NAV]
            blocks = [b for b in blocks if b != SHOWCASE_NAV]
    want_b, want_s, support = resolve(lib, blocks, screens)
    spec = {
        "blocks": [dict(b) for b in lib["blocks"] if b["name"] in want_b],
        "screens": [dict(s) for s in lib["screens"] if s["name"] in want_s],
    }
    for k in SUPPORT:
        items = [e for e in lib.get(k, []) if e["name"] in support[k]]
        if items:
            spec[k] = items
    for item in spec["blocks"] + spec["screens"]:
        item["flow"] = args.flow
    out = pathlib.Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    names = list(want_b) + list(want_s) + [n for k in SUPPORT for n in support[k]] + ["OuiCore"] + list(LIBRARIES)
    rn = renamer(names, args.rename, list(support["entities"]) + list(support["staticEntities"]))
    core = rn("OuiCore")
    # The script finds its own file and its libraries by name, so a rename reaches it too.
    (out / "oui-core.js").write_text(rn(js), encoding="utf-8", newline="\n")
    spec["scripts"] = [{"name": core, "file": "oui-core.js"}]
    if want_b & MARKDOWN_BLOCKS:
        for name, file in LIBRARIES.items():
            shutil.copyfile(HERE / "vendor" / file, out / file)
            spec["scripts"].append({"name": name, "file": file})
    used = set(re.findall(r"oui-[a-z0-9_-]*[a-z0-9]", dump(spec))) | set(re.findall(r"oui-[a-z0-9_-]*[a-z0-9]", js))
    kit_css = strip_comments(css) if everything else slice_css(css, used | UTILITIES)
    (out / "oui-kit.css").write_text(kit_css + "\n", encoding="utf-8", newline="\n")
    if args.new_theme:
        # A module with no theme of its own (a new app uses OutSystems UI's): a theme based on OutSystemsUI that holds
        # the kit CSS, made the module's default theme.
        (out / "theme.css").write_text(kit_css + "\n", encoding="utf-8", newline="\n")
        spec["themes"] = [{"name": args.new_theme, "styleSheet": {"file": "theme.css"}, "baseTheme": "OutSystemsUI"}]
        spec["module"] = {"defaultTheme": args.new_theme}
    elif args.theme:
        if not args.current:
            sys.exit("--theme needs --current <current.css>: the theme's CSS now (oml describe <app.oml> <Theme> --css).")
        current = pathlib.Path(args.current).read_text(encoding="utf-8")
        if MARK in current:
            current = current[:current.index(MARK)].rstrip()
        (out / "theme.css").write_text(current.rstrip() + "\n\n" + MARK + "\n" + kit_css + "\n", encoding="utf-8", newline="\n")
        spec["themes"] = [{"name": args.theme, "styleSheet": {"file": "theme.css"}}]
    text = rn(dump(spec))
    (out / "spec.json").write_text(json.dumps(json.loads(text), indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({
        "spec": str(out / "spec.json"), "blocks": sorted(rn(n) for n in want_b), "screens": sorted(rn(n) for n in want_s),
        "support": {k: sorted(rn(n) for n in v) for k, v in support.items() if v}, "script": core,
        "css": {"bytes": len(kit_css), "of": len(strip_comments(css))}, "theme": args.new_theme or args.theme,
        "next": f"oml spec check {out / 'spec.json'}; oml apply <app.oml> {out / 'spec.json'} <new staged.oml>"
                + ("" if args.theme or args.new_theme else f". Add {out / 'oui-kit.css'} to the app's theme (append; keep its own CSS), or use --new-theme."),
    }, indent=1))


def walk_widgets(w, visit):
    if isinstance(w, dict):
        visit(w)
        for v in w.values():
            walk_widgets(v, visit)
    elif isinstance(w, list):
        for v in w:
            walk_widgets(v, visit)


def catalog(args):
    lib, css, js = load()
    examples, users = {}, {}
    for s in lib["screens"] + lib["blocks"]:
        def visit(w, owner=s["name"]):
            if w.get("type") == "BlockInstance" and w.get("sourceBlock"):
                examples.setdefault(w["sourceBlock"], w)
                users.setdefault(w["sourceBlock"], set()).add(owner)
        walk_widgets(s.get("widgets"), visit)
    screen_names = {s["name"] for s in lib["screens"]}
    items = []
    for b in lib["blocks"]:
        holders = []
        walk_widgets(b.get("widgets"), lambda w: holders.append(w["name"]) if w.get("type") == "Placeholder" and w.get("name") else None)
        items.append({
            "name": b["name"], "description": b.get("description", ""),
            "inputs": [{k: i[k] for k in ("name", "type", "mandatory", "default", "description") if k in i} for i in b.get("inputs", [])],
            "events": [{"name": e["name"], "inputs": [i["name"] + ": " + i.get("type", "Text") for i in e.get("inputs", [])]} for e in b.get("events", [])],
            "placeholders": holders, "uses": sorted(resolve(lib, [b["name"]], [])[0] - {b["name"]}),
            "shownOn": sorted(u for u in users.get(b["name"], ()) if u in screen_names), "example": examples.get(b["name"]),
        })
    KIT.mkdir(exist_ok=True)
    (KIT / "catalog.json").write_text(json.dumps({"blocks": items}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    lines = ["# OUI component catalog", "",
             f"{len(items)} blocks and {len(lib['screens'])} screens. Build any of them in your own module: `python ouikit.py --blocks A,B --out <folder>` (dependencies",
             "included), then `oml apply`. Per block: what it does, inputs (`*` mandatory), events, placeholders, blocks it uses, the OUI screen that shows it.", "",
             "# Page templates", "", "Build one with `--screens <Name>`. Replace the Load action with your own data.", ""]
    for s in lib["screens"]:
        if s["name"].startswith(TEMPLATE_PREFIX):
            lines += [f"- **{s['name']}**: {s.get('description', '')}"]
    lines += ["", "# Blocks", ""]
    for it in items:
        ins = ", ".join(("*" if i.get("mandatory") else "") + i["name"] + ": " + i.get("type", "Text") + (f" = {i['default']}" if "default" in i else "") for i in it["inputs"]) or "none"
        lines += [f"## {it['name']}", it["description"], f"- Inputs: {ins}"]
        if it["events"]: lines.append("- Events: " + ", ".join(f"{e['name']}({', '.join(e['inputs'])})" for e in it["events"]))
        if it["placeholders"]: lines.append("- Placeholders: " + ", ".join(it["placeholders"]))
        if it["uses"]: lines.append("- Uses: " + ", ".join(it["uses"]))
        if it["shownOn"]: lines.append("- Shown on: " + ", ".join(it["shownOn"]))
        if it["example"]: lines.append("- Example: `" + json.dumps(it["example"], ensure_ascii=False)[:400] + "`")
        lines.append("")
    (KIT / "catalog.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(json.dumps({"catalog": str(KIT / "catalog.md"), "blocks": len(items)}))


GUIDE = """# OUI kit: build OUI components in any OutSystems 11 Reactive module

Service Studio refuses to paste OUI into a module of another infrastructure. This kit builds the components again from source.

You need Python 3 and `oml`. The target module must be open in Service Studio (or be a local .oml file).

## Steps

1. Read `kit/catalog.md`. Choose blocks by their description. Page templates are at the top.
2. Build the spec:
   - Some components: `python ouikit.py --blocks OuiCard,OuiTableWrap --new-theme AppTheme --out build`
   - One page template: `python ouikit.py --screens OuiTplDashboard --new-theme AppTheme --out build`
   - Everything: `python ouikit.py --all --new-theme AppTheme --out build`
3. Apply: `oml apply <App.oml> build/spec.json <new staged.oml>`. Expect `saved: true` and no `newErrors`.
4. Install and publish after the person says yes.

## Options

- `--rename Oui=Acme` renames every element, so the names fit your project.
- `--flow UI` puts screens and blocks in that UI flow (the default is UI).
- The module has its own theme: `oml describe <App.oml> <Theme> --css`, save its style sheet to a file, then use `--theme <Theme> --current <file>` instead of `--new-theme`. Your CSS stays.

## Notes

- Dependencies come with the block: other blocks, structures, entities, actions and the script.
- Screens are for registered users. Change their access only if the person asks.
- Templates use demo data. Replace the Load action with an aggregate.
- Blocks that use demo entities need them. The kit adds them.
- `InvalidResourceURL_Offline` on the theme is expected: a checkbox icon is inside the CSS. It matters only for offline mobile apps.
"""


def pack(args):
    out = pathlib.Path(args.pack).resolve()
    for sub_dir in ("js", "vendor", "kit"):
        (out / sub_dir).mkdir(parents=True, exist_ok=True)
    for name in ("ouikit.py", "library.json", "theme.css"):
        shutil.copyfile(HERE / name, out / name)
    shutil.copyfile(HERE / "js" / "module.js", out / "js" / "module.js")
    for f in (HERE / "vendor").iterdir():
        shutil.copyfile(f, out / "vendor" / f.name)
    for name in ("catalog.json", "catalog.md"):
        shutil.copyfile(KIT / name, out / "kit" / name)
    (out / "README.md").write_text(GUIDE, encoding="utf-8", newline="\n")
    print(json.dumps({"pack": str(out), "guide": str(out / "README.md")}))


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--catalog", action="store_true")
    p.add_argument("--blocks"); p.add_argument("--screens")
    p.add_argument("--all", action="store_true", help="every block and screen")
    p.add_argument("--all-blocks", action="store_true", help="every block, no screens")
    p.add_argument("--pack", help="copy the kit to a folder of its own")
    p.add_argument("--flow", default="UI")
    p.add_argument("--rename", help="Oui=Acme renames every OUI element name that starts with Oui")
    p.add_argument("--theme"); p.add_argument("--current")
    p.add_argument("--new-theme", help="a module without its own theme: create this theme (base OutSystemsUI) with the kit CSS and make it the default")
    p.add_argument("--out")
    a = p.parse_args()
    if a.catalog:
        catalog(a)
    elif a.pack:
        pack(a)
    elif a.out and (a.blocks or a.screens or a.all or a.all_blocks):
        build(a)
    else:
        p.print_help()
