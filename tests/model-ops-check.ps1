# Generic model operations (edits add, remove, move, typed set) and the official skill's use cases as specs.
#   tests/model-ops/seed.json + ops-positive.json   add, remove, move, typed set on existing elements: saves, order as asked
#   tests/model-ops/refusals.json                   each refusal (production rule, unknown type or member, bad value) with its message
#   tests/model-ops/examples-seed.json + examples.json   one spec per use case of the official skill's examples/*.cs
# -WriteTable rewrites tests/model-ops/examples.md (the example -> spec table) from examples.json.
param([string]$Oml, [string]$Tmp, [switch]$WriteTable)
$ErrorActionPreference = 'Stop'
function Require($condition, $message) { if (-not $condition) { throw "model-ops: $message" } }
$dir = Join-Path $PSScriptRoot 'model-ops'
$work = Join-Path $Tmp 'model-ops'
if (Test-Path $work) { Remove-Item -Recurse -Force $work }
New-Item -ItemType Directory -Force $work | Out-Null
function Apply($source, $spec, $name) {
  $out = Join-Path $work "out-$name.oml"
  $text = (& $Oml apply $source $spec $out 2>$null) -join "`n"
  return [pscustomobject]@{ Report = ($text | ConvertFrom-Json); Text = $text; Out = $out }
}
function Attributes($module, $entity) {
  @((& $Oml tree $module $entity --depth 1 | ConvertFrom-Json).children | Where-Object kind -eq 'EntityAttribute' | ForEach-Object name) -join ','
}

# 1. Generic operations on existing elements.
& $Oml new (Join-Path $work 'blank.oml') --name Ops --kind CrossDevice | Out-Null
$seeded = Join-Path $work 'seeded.oml'
$r = (& $Oml apply (Join-Path $work 'blank.oml') (Join-Path $dir 'seed.json') $seeded) | ConvertFrom-Json
Require ($r.saved) "seed did not save: $($r | ConvertTo-Json -Depth 6 -Compress)"
$p = Apply $seeded (Join-Path $dir 'ops-positive.json') 'positive'
Require ($p.Report.saved -and $p.Report.summary.newErrors -eq 0) "ops-positive: $($p.Text)"
$order = Attributes $p.Out 'Customer'
Require ($order -eq 'Phone,Id,Score,Name,Email,Discount') "attribute order after add first/after and move before: $order"
$check = (& $Oml spec check (Join-Path $dir 'ops-positive.json')) | ConvertFrom-Json
Require ($check.ok) "spec check of ops-positive: $($check | ConvertTo-Json -Compress)"

# 2. Refusals: each with the message that tells the agent what to do.
$bad = @()
foreach ($case in (Get-Content -Raw (Join-Path $dir 'refusals.json') | ConvertFrom-Json)) {
  $file = Join-Path $work "$($case.name).json"
  $case.spec | ConvertTo-Json -Depth 20 | Set-Content -Encoding utf8 $file
  if ($case.where -eq 'check') { $text = (& $Oml spec check $file) -join "`n"; $ok = $LASTEXITCODE -eq 1 }
  else { $a = Apply $seeded $file $case.name; $text = $a.Text; $ok = -not $a.Report.saved }
  if (-not ($ok -and $text.Contains($case.expect))) { $bad += "$($case.name): $text" }
}
Require ($bad.Count -eq 0) "refusals: $($bad -join ' | ')"

# 3. The official skill's use cases.
& $Oml new (Join-Path $work 'shop0.oml') --name Shop --kind CrossDevice | Out-Null
& $Oml new (Join-Path $work 'web.oml') --name ShopWeb --kind WebResponsive | Out-Null
$shop = Join-Path $work 'shop.oml'
$r = (& $Oml apply (Join-Path $work 'shop0.oml') (Join-Path $dir 'examples-seed.json') $shop) | ConvertFrom-Json
Require ($r.saved) "examples seed did not save"
$bases = @{ seed = $shop; web = (Join-Path $work 'web.oml') }
$cases = Get-Content -Raw (Join-Path $dir 'examples.json') | ConvertFrom-Json
$failed = @()
foreach ($case in $cases) {
  $file = Join-Path $work "case-$($case.id).json"
  ($case.spec | ConvertTo-Json -Depth 30).Replace('{seed}', $shop.Replace('\', '/')) | Set-Content -Encoding utf8 $file
  $a = Apply $bases[$case.base] $file $case.id
  $ok = if ($case.PSObject.Properties['expect']) { -not $a.Report.saved -and $a.Text.Contains($case.expect) } else { $a.Report.saved -and $a.Report.summary.newErrors -eq 0 }
  if (-not $ok) { $failed += "$($case.id): $($a.Text.Substring(0, [Math]::Min(600, $a.Text.Length)))" }
}
Require ($failed.Count -eq 0) "examples: $($failed -join ' | ')"
Require ((Attributes (Join-Path $work 'out-attribute-reorder.oml') 'Customer') -eq 'Id,IsActive,Name,Email') "move in attribute-reorder"
$link = (& $Oml describe (Join-Path $work 'out-link-destination.oml') Orders --depth 3) -join "`n"
Require ($link.Contains('NewOrderLink onClick=NewOrder')) "set onClick on an existing link"

if ($WriteTable) {
  $lines = @('# The official skill''s examples as specs', '',
    'Generated by `tests/model-ops-check.ps1 -WriteTable` from examples.json; do not edit by hand. Each row is tested: the spec',
    'applies to the module of examples-seed.json (or a blank Traditional Web module) with no new errors, or is refused with the',
    'message shown. The examples are the official OutSystems skill''s examples/*.cs and integration-examples/*.md.', '',
    '| Example | Spec (examples.json id) | Spec keys | Result |', '|---|---|---|---|')
  foreach ($case in $cases) {
    $keys = if ($case.PSObject.Properties['key']) { $case.key } else {
      (@($case.spec.PSObject.Properties.Name | Where-Object { $_ -ne 'edits' }) + @($case.spec.edits | ForEach-Object { "edits $($_.op)" })) -join ', ' }
    $result = if ($case.PSObject.Properties['expect']) { "refused: ""$($case.expect)""" } else { 'applies' }
    $lines += "| $($case.examples -join ', ') | ``$($case.id)`` | $keys | $result |"
  }
  ($lines -join "`n") + "`n" | Set-Content -Encoding utf8 -NoNewline (Join-Path $dir 'examples.md')
}
Write-Host "ok   model-ops: add/remove/move/typed set, $(@((Get-Content -Raw (Join-Path $dir 'refusals.json') | ConvertFrom-Json)).Count) refusals, $($cases.Count) use cases of the official skill"
